                <ul>
                    <li><strong>Nombre completo:</strong> Tamaño destacado (18-20pt) y legible.</li>
                    <li><strong>Datos esenciales:</strong> Teléfono, email profesional y ubicación (Ciudad, País).</li>
                    <li><strong>Enlaces profesionales:</strong> LinkedIn obligatorio; GitHub y portafolio interactivo para roles técnicos.</li>
                    <li><strong class="text-danger">Exclusiones estrictas:</strong> Cero fotos, edad, estado civil o fecha de nacimiento.</li>
                </ul>
            </div>

            <!-- 2. Resumen -->
            <div class="guide-card">
                <div class="guide-card-icon">🎯</div>
                <h4>2. Resumen Profesional (Elevator Pitch)</h4>
                <ul>
                    <li><strong>Longitud:</strong> 3 a 4 líneas de alto impacto.</li>
                    <li><strong>Propuesta de valor:</strong> Quién eres, especialidad técnica y qué dolor resuelves a la empresa.</li>
                    <li><strong class="text-danger">Prohibido clichés:</strong> Cero palabras vacías como <em>"proactivo"</em> o <em>"trabajador en equipo"</em>; usa hechos concretos.</li>

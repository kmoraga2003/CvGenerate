                <ul>
                    <li><strong>Cronología inversa:</strong> Del puesto más reciente al más antiguo.</li>
                    <li><strong>Fórmula XYZ (Modelo Google):</strong> <em>"Logré [X], medido por [Y], haciendo [Z]"</em>.</li>
                    <li><strong>Verbos de Acción Fuerte:</strong> Inicia cada viñeta con <em>Optimizé, Dirigí, Diseñé, Implementé, Desplegué</em>.</li>
                    <li><strong>Métricas obligatorias:</strong> Porcentajes (%), volumen de usuarios, latencia o montos ahorrados.</li>
                </ul>
